#!/usr/bin/env python3
"""Genera internal/ui/icons_table.go a partir de la misma tabla que usa el diseño.

Lee SET de make-icons.py (iconos, colores, nombres exactos y extensiones) y los codepoints de src/icons.js
(ya generado con las fuentes Nerd Font), de modo que el editor y las maquetas comparten una sola fuente de verdad.

Uso (desde la raíz del repositorio):
  python3 docs/design/tools/make-icons-go.py
"""
import ast, re, subprocess

root = 'docs/design/'
src = open(root + 'tools/make-icons.py', encoding='utf-8').read()
start = src.index('SET = {') + len('SET = ')
end = src.index('\n}\n', start) + 2
table = ast.literal_eval(src[start:end])
codes = dict(re.findall(r'"(\w+)":\{"d":"[^"]*","w":[\d.]+,"h":[\d.]+,"code":"U\+([0-9A-F]+)"', open(root + 'src/icons.js', encoding='utf-8').read()))

def glyph(key):
    cp = int(codes[key], 16)
    return '"\\U%08x"' % cp

out = ['// Code generated by docs/design/tools/make-icons-go.py; DO NOT EDIT.', '',
       'package ui', '',
       '// iconDefs relaciona la clave de cada icono con su glifo de Nerd Font y el color de la paleta (clave del tema).',
       'var iconDefs = map[string]Icon{']
for key in table:
    out.append('\t%-14s{Glyph: %s, Color: "%s"},' % ('"%s":' % key, glyph(key), table[key][1]))
out += ['}', '', '// iconByName: nombre exacto de archivo → clave de icono.', 'var iconByName = map[string]string{']
for key, (_, _, exact, _) in table.items():
    for n in exact:
        out.append('\t%-28s"%s",' % ('"%s":' % n, key))
out += ['}', '', '// iconByExt: extensión en minúsculas (sin punto) → clave de icono.', 'var iconByExt = map[string]string{']
for key, (_, _, _, exts) in table.items():
    for e in exts:
        out.append('\t%-14s"%s",' % ('"%s":' % e, key))
out.append('}')
open('internal/ui/icons_table.go', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
subprocess.run(['gofmt', '-w', 'internal/ui/icons_table.go'], check=True)
print('icons_table.go:', len(table), 'iconos')
